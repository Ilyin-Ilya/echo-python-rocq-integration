#!/usr/bin/env python3
"""Generate data-only legacy Echo oracles for generic-IR migration checks.

The old Rocq executable model remains a temporary proof and test oracle.  This
generator exports only its evaluated program and expected vectors; it emits no
Python transition implementation.  The generic interpreter is the sole Python
executor used to replay these vectors.
"""

from __future__ import annotations

import argparse
import hashlib
import pprint
import sys
from pathlib import Path
from typing import Sequence

if __package__:
    from . import rocq_codegen
    from .migration import legacy_echo_export as legacy
else:
    import rocq_codegen
    from migration import legacy_echo_export as legacy


def render_oracle_data(
    program: tuple,
    program_sexpr: str,
    evaluation_vectors: tuple,
    evaluation_vectors_sexpr: str,
    run_vectors: tuple,
    run_vectors_sexpr: str,
) -> str:
    """Render immutable literals; deliberately emit no executable behavior."""

    program_digest = hashlib.sha256(program_sexpr.encode("utf-8")).hexdigest()
    vectors_digest = hashlib.sha256(
        evaluation_vectors_sexpr.encode("utf-8")
    ).hexdigest()
    run_vectors_digest = hashlib.sha256(
        run_vectors_sexpr.encode("utf-8")
    ).hexdigest()
    literal = lambda value: pprint.pformat(
        value, width=88, compact=False, sort_dicts=False
    )
    return f'''# Generated by tools/generate_echo_oracles_from_rocq.py; do not edit.
"""Data-only Rocq migration oracles for the generic Echo IR interpreter.

This module contains no transition function, runner, classes, or imports.
Its values are temporary comparison evidence and are never used by production.
"""

ORACLE_SCHEMA_VERSION = 1
ROCQ_LEGACY_PROGRAM_SHA256 = {program_digest!r}
ROCQ_LEGACY_PROGRAM_SEXPR = {program_sexpr!r}
ROCQ_LEGACY_PROGRAM = {literal(program)}
ROCQ_EVALUATION_VECTORS_SHA256 = {vectors_digest!r}
ROCQ_EVALUATION_VECTORS_SEXPR = {evaluation_vectors_sexpr!r}
ROCQ_EVALUATION_VECTORS = {literal(evaluation_vectors)}
ROCQ_RUN_VECTORS_SHA256 = {run_vectors_digest!r}
ROCQ_RUN_VECTORS_SEXPR = {run_vectors_sexpr!r}
ROCQ_RUN_VECTORS = {literal(run_vectors)}
'''


def main(argv: Sequence[str] | None = None) -> int:
    repository = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rocq-project",
        type=Path,
        default=repository.parent / "echo-algorithm-coq",
    )
    parser.add_argument(
        "--program-output",
        type=Path,
        default=repository / "bridge" / "rocq_echo_program.sexp",
    )
    parser.add_argument(
        "--vectors-output",
        type=Path,
        default=repository / "bridge" / "rocq_echo_vectors.sexp",
    )
    parser.add_argument(
        "--run-vectors-output",
        type=Path,
        default=repository / "bridge" / "rocq_echo_run_vectors.sexp",
    )
    parser.add_argument(
        "--python-output",
        type=Path,
        default=repository
        / "distributed_simulations"
        / "migration"
        / "generated_echo_oracles.py",
    )
    parser.add_argument("--coqtop")
    parser.add_argument("--rocqlib")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)

    try:
        coqtop = rocq_codegen.find_coqtop(arguments.coqtop)
        rocqlib = rocq_codegen.find_rocqlib(arguments.rocqlib)
        program_sexpr, vectors_sexpr, run_vectors_sexpr = (
            legacy.evaluate_rocq_exports(
                arguments.rocq_project.resolve(), coqtop, rocqlib
            )
        )
        program = rocq_codegen.parse_sexpr(program_sexpr)
        vectors = rocq_codegen.parse_sexpr(vectors_sexpr)
        run_vectors = rocq_codegen.parse_sexpr(run_vectors_sexpr)
        legacy.validate_program(program)
        legacy.validate_evaluation_vectors(vectors)
        legacy.validate_run_vectors(run_vectors)
        rendered = render_oracle_data(
            program,
            program_sexpr,
            vectors,
            vectors_sexpr,
            run_vectors,
            run_vectors_sexpr,
        )
        outputs = (
            (arguments.program_output.resolve(), program_sexpr + "\n"),
            (arguments.vectors_output.resolve(), vectors_sexpr + "\n"),
            (arguments.run_vectors_output.resolve(), run_vectors_sexpr + "\n"),
            (arguments.python_output.resolve(), rendered),
        )
        current = all(
            rocq_codegen.write_or_check(path, content, arguments.check)
            for path, content in outputs
        )
    except (legacy.GenerationError, rocq_codegen.GenerationError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if arguments.check and not current:
        print("error: generated Echo oracle data is stale", file=sys.stderr)
        return 1
    action = "checked" if arguments.check else "generated"
    print(
        f"{action} data-only Echo migration oracles "
        f"({len(vectors) - 2} steps, {len(run_vectors) - 1} runs)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
