"""Reproducible topology and mutation evaluation for Echo exploration."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

from .echo_explorer import MUTATIONS, explore_echo
from .echo_topologies import (
    binary_tree_topology,
    dense_topology,
    line_topology,
    ring_topology,
)


def run_evaluation() -> Dict[str, Any]:
    cases = (
        ("line-5", line_topology(5)),
        ("binary-tree-7", binary_tree_topology(7)),
        ("ring-5", ring_topology(5)),
        ("dense-4", dense_topology(4)),
    )
    topology_results: List[Dict[str, Any]] = []
    for name, topology in cases:
        result = explore_echo(topology, max_depth=40, max_states=100_000)
        topology_results.append({"name": name, **result.to_dict()})

    mutation_results: List[Dict[str, Any]] = []
    mutation_topology = ring_topology(4)
    for mutation in MUTATIONS:
        result = explore_echo(
            mutation_topology,
            max_depth=20,
            max_states=100_000,
            mutation=mutation,
        )
        mutation_results.append({"mutation": mutation, **result.to_dict()})
    detected = sum(not result["safe"] for result in mutation_results)
    return {
        "bounds": {"max_depth": 40, "max_states": 100_000},
        "topologies": topology_results,
        "mutations": mutation_results,
        "mutation_detection": {
            "detected": detected,
            "total": len(mutation_results),
            "rate": detected / len(mutation_results),
        },
    }


def render_markdown(evaluation: Dict[str, Any]) -> str:
    lines = [
        "# Echo bounded-exploration evaluation",
        "",
        "Generated by `python -m distributed_simulations.algorithms.echo_evaluation`.",
        "The exploration enumerates all delivery choices within the stated bounds;",
        "it complements but does not replace the symbolic Rocq proof.",
        "",
        "## Valid implementations",
        "",
        "| Topology | States | Transitions | Duplicates | Complete | Stuck | Bounded | Safe |",
        "|---|---:|---:|---:|---:|---:|---:|:---:|",
    ]
    for result in evaluation["topologies"]:
        lines.append(
            f"| {result['name']} | {result['explored_states']} | "
            f"{result['explored_transitions']} | {result['duplicate_states']} | "
            f"{result['completed_states']} | {result['stuck_states']} | "
            f"{result['bounded_states']} | {'yes' if result['safe'] else 'no'} |"
        )
    lines.extend(
        [
            "",
            "## Mutation detection on ring-4",
            "",
            "| Mutation | Detected | Shortest delivery-ID path |",
            "|---|:---:|---|",
        ]
    )
    for result in evaluation["mutations"]:
        path = result["violation"]["path"] if result["violation"] else []
        lines.append(
            f"| {result['mutation']} | {'yes' if not result['safe'] else 'no'} | "
            f"`{path}` |"
        )
    detection = evaluation["mutation_detection"]
    lines.extend(
        [
            "",
            f"Detection rate: **{detection['detected']}/{detection['total']} "
            f"({detection['rate']:.0%})**.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="print JSON instead")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    evaluation = run_evaluation()
    output = (
        json.dumps(evaluation, indent=2, sort_keys=True) + "\n"
        if args.json
        else render_markdown(evaluation)
    )
    if args.output is None:
        print(output, end="")
    else:
        args.output.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
